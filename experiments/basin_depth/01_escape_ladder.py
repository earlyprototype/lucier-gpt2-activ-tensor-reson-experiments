"""How far must a settled state be rotated before it does not come home?

Registered before execution in issue #17 (the 2026-08-04 registration comment;
read that and the 2026-08-04 context comment before the issue body, whose
original motivation was refuted by run 17).

THE MEASURE IS AN ANGLE. The loop rescales every iterate to a fixed size, so
a state never leaves a sphere. Pushing it and rescaling back is therefore a
rotation, and the escape threshold is reported in DEGREES rotated away from
the attractor. That is dimensionless, comparable across injection scales, and
directly comparable to run 18's finding that inside the band the loop itself
rotates the state about 77 degrees on an ordinary pass. The question this
answers: how far must a settled state be rotated before the loop stops
bringing it back, measured against how far the loop moves it anyway?

No prediction was registered for whether the threshold exceeds the per-pass
turn. If it turns out smaller, then a rotation gentler than the loop's own
routine motion suffices to dislodge a state, and "basin" would be a
misleading word for these objects; the record would have to say so.

WHAT A ROTATION MEANS HERE. The state is a [positions, 768] tensor. It is
treated as a single point on a sphere in the flattened space, so a direction
is a full-tensor direction, made perpendicular to the state and unit length
(a parallel push only changes size, which the rescale undoes). Rotating by
theta gives  x' = |x| (cos(theta) x_hat + sin(theta) v_hat).  Named
directions, which live in the 768-dimensional per-position space, are
broadcast to every position before being orthogonalised.

SELF-VERIFICATION RATHER THAN A SYNTHETIC CONTRACT. Converged states are
regenerated by iterating, because the sweep archived only each trial's mean
and last vectors, not the full tensor. The regeneration is checked directly
against committed data: the recovered state's readout token must equal the
terminal token the sweep recorded for that same level and prompt. The flip
axis is likewise recomputed and gated against experiment 07's committed
scalars (its norm and its cosine with the pivot), because the committed
Divine snapshots are sampled ten iterations apart and so all sit on the same
phase of the period-2 cycle, which is the aliasing F9 documents.

Run from the repo root:

    ATR_GPT2_LOCAL=... python3 experiments/basin_depth/01_escape_ladder.py --prepare
    ATR_GPT2_LOCAL=... python3 experiments/basin_depth/01_escape_ladder.py --worker 0 --num-workers 4
    python3 experiments/basin_depth/01_escape_ladder.py --report-only

Outputs (in experiments/basin_depth/output/):
    directions.pt              the named directions, with their gate results
    checkpoints/<key>.pt       one file per (state, direction) ladder
    escape_ladder.pt           combined archive
    escape_ladder.md           every headline number, from the data only
"""

